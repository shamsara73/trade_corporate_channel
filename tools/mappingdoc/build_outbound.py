"""Render docs/outbound/<message>.md from sources/ti_outbound/<message>.txt.

    python3 -I tools/mappingdoc/build_outbound.py

The crosswalk to the inbound TFUTIAPP schema is checked: a path that does not
exist in the schema fails the build.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, '..', 'specgen'))
import mapping_lib as M  # noqa: E402
import crosswalk_tfutiapp as X  # noqa: E402
import specgen_lib as L  # noqa: E402
import eventfields_lib as E  # noqa: E402

EVENT_LISTS = E.load_all()
DESC_SOURCE = 'IGT_IIG'


def ti_desc(f):
    """Description of the field's event field code from the TI event field list, or None."""
    if f['type'] == 'literal':
        return None
    fields = EVENT_LISTS[DESC_SOURCE][0]
    return fields.get((f['tag'], f['type']))

OUT = os.path.join(M.ROOT, 'docs', 'outbound')
GROUP_TITLES = [
    'Message identity', 'Event flags', 'Instruction context', 'Narratives',
    'Applicant', 'Principal and branch', 'Principal if not the applicant', 'Beneficiary',
    'Issuing bank', 'Final issuing bank', 'Advising bank', 'Advise-through bank',
    'Advise-through bank (local)', 'Confirming bank', 'Requested confirmation party',
    'Counter-undertaking to send: terms', 'Counter-undertaking to send: amount', 'Counter-undertaking to send: text',
    'Counter-undertaking to send: available with', 'Counter-undertaking to send: renewal',
    'Counter-undertaking to send: reduction / increase', 'Counter-undertaking to send: irregular schedule',
    'Undertaking: terms', 'Undertaking: amount and liability', 'Undertaking: text',
    'Undertaking: available with', 'Undertaking: wording and transfer', 'Undertaking: renewal',
    'Undertaking: reduction / increase', 'Undertaking: irregular schedule',
    'Delivery, confirmation, charges, accounts', 'Contract details', 'Shipment and product',
    'Charges (table)', 'Attached documents (table)', 'Linked licences (table)']
SUFFIX = {'S': 'counter-undertaking to send', 'U': 'undertaking'}
SCHEMA = L.parse('TFUTIAPP')
PATHS = {n.path for n in SCHEMA.walk()}


def resolve(f):
    """Return (schema path or None, confidence, note) for a field."""
    tag, base, suf = f['tag'], f.get('base'), f.get('suffix')
    typ, sub = f['type'], f.get('sub')
    if f['type'] == 'literal':
        return None, '', 'literal text defined in the mapping'
    key = tag if tag in X.COMMON else base
    if suf in ('S', 'U') and base not in X.COMMON:
        root = 'UndertakingDetails/' + ('CounterToSend' if suf == 'S' else 'Undertaking')
        if X.U.get((base, sub), 0) is None:
            return None, '', 'currency of the previous amount field'
        e = X.U.get((base, sub)) or X.U.get((base, typ)) or X.U.get(base)
        if e is None:
            return None, '', X.TI_ONLY.get(base, '')
        path, conf, note = e
        path = path.replace('@', root + '/', 1) if path.startswith('@') else path
        return path, conf, note
    e = X.COMMON.get((base, sub)) or X.COMMON.get(tag) or X.COMMON.get(base)
    if e:
        path, conf, note = e
        if path is None:
            return None, conf, note
        return path, conf, note
    if base in X.TI_ONLY or tag in X.TI_ONLY:
        return None, '', X.TI_ONLY.get(tag) or X.TI_ONLY.get(base)
    return None, '', ''


def check_paths(rows):
    bad = [(n, p) for n, p in rows if p and p not in PATHS and not p.startswith('Context/')]
    if bad:
        raise SystemExit('crosswalk paths not in TFUTIAPP schema: %s' % bad)


def type_text(f):
    t = M.TYPES[f['type']]
    sub = f.get('sub')
    if f['type'] == 'p':
        return 'party' + (' – ' + M.PARTY_SUB.get(sub, sub) if sub else '')
    if f['type'] == 'v':
        return 'value – ' + M.VALUE_SUB.get(sub, sub or '')
    if f['type'] == 'd':
        return 'date' + (' (format %s)' % sub if sub and sub != '%' else '')
    if f['type'] == '*':
        return 'table: ' + ', '.join(c['name'] for c in f['columns'])
    return t + (' (%s)' % sub if sub and sub != '%' else '')


def render(name):
    groups = M.load(name)
    fields = [f for g in groups for f in g]
    out = ['# %s – TI outward message mapping' % name, '',
           '> Generated by `tools/mappingdoc/build_outbound.py` from `sources/ti_outbound/%s.txt`. Do not edit. '
           'Index and notation: [README](README.md).' % name, '']
    n_party = sum(1 for f in fields if f['type'] == 'p')
    out += ['| | |', '|---|---|',
            '| Fields | %d (in %d groups; %d are party sub-fields) |' % (len(fields), len(groups), n_party),
            '| Of these | %d for the **undertaking** (`-U`), %d for the **counter-undertaking to send** (`-S`), %d without suffix |' % (
                sum(1 for f in fields if f.get('suffix') == 'U'), sum(1 for f in fields if f.get('suffix') == 'S'),
                sum(1 for f in fields if f['type'] != 'literal' and not f.get('suffix'))),
            '| Tables | %s |' % ', '.join('`%s`' % f['name'] for f in fields if f['type'] == '*'),
            '']
    checked = []
    anomalies = []
    out += ['## Fields', '',
            '"TI event field" is the description of the tag in TI\'s own event field list for the IGT issue event (`sources/ti_outbound/IGT_IIG_All_E.csv`, see [event-fields-IGT-IIG](event-fields-IGT-IIG.md)). '
            'Confidence in the schema counterpart: **H** name and structure agree, **M** plausible, **L** guess, – none found. '
            'Counterparts are paths in the inbound [`TFUTIAPP`](../products/undertaking-issued.md) schema; for `-S` fields the path is under `UndertakingDetails/CounterToSend`, for `-U` fields under `UndertakingDetails/Undertaking`.', '']
    for gi, g in enumerate(groups):
        out += ['### %d. %s' % (gi + 1, GROUP_TITLES[gi]), '']
        if g[0]['type'] == 'p' and all(f['type'] == 'p' for f in g):
            base = g[0]['base'] + ('-' + g[0]['suffix'] if g[0]['suffix'] else '')
            path, conf, note = resolve(g[0])
            checked.append((g[0]['name'], path))
            out_desc = ti_desc(g[0])
            subs = ', '.join('`%s` (%s)' % (f['name'], M.PARTY_SUB.get(f.get('sub'), f.get('sub') or 'name')) for f in g)
            out += ['Party block, tag `%s`%s: %s' % (base, ' (TI: %s)' % out_desc if out_desc else '', subs), '',
                    'Schema counterpart: %s%s%s' % ('`%s`' % path if path else '–', ' (%s)' % conf if conf else '', ' – ' + note if note else ''), '']
            continue
        out += ['| Field | Tag | Type | TI event field | Schema counterpart | Conf. | Note |', '|---|---|---|---|---|---|---|']
        for f in g:
            path, conf, note = resolve(f)
            checked.append((f['name'], path))
            if f['type'] == 'literal':
                tagtxt, tx = '`TEXT`', 'literal "%s"' % f['literal']
            else:
                tagtxt, tx = '`%s`' % f['tag'], type_text(f)
            d = ti_desc(f)
            if f['type'] != 'literal' and d is None:
                d = '**not in the %s event field list**' % DESC_SOURCE.replace('_', ' ')
            out.append('| `%s` | %s | %s | %s | %s | %s | %s |' % (
                f['name'], tagtxt, tx, d or '–', '`%s`' % path if path else '–', conf or '–', note))
        out.append('')
    check_paths(checked)
    # anomalies
    seen = {}
    for f in fields:
        if f['type'] in ('literal', '*'):
            continue
        seen.setdefault((f['tag'], f['type'], f.get('sub')), []).append(f['name'])
    shared = {k: v for k, v in seen.items() if len(v) > 1 and not (k[1] == 'p')}
    dup = sorted({f['name'] for f in fields if [g['name'] for g in fields].count(f['name']) > 1})
    unmapped = [f['name'] for f in fields if f['type'] not in ('literal',) and resolve(f)[0] is None and not resolve(f)[2]]
    low = [f['name'] for f in fields if resolve(f)[1] == 'L']
    missing = sorted({(f['name'], f['tag']) for f in fields if f['type'] != 'literal' and ti_desc(f) is None})
    out += ['## Points to check with the TI team', '']
    out += ['* **Same tag, same type, different field name:** ' + '; '.join(
        '%s share `%s`' % (' and '.join('`%s`' % n for n in v), k[0] + (',' + k[2] if k[2] else '')) for k, v in sorted(shared.items())) + '. If these are meant to differ, the mapping gives them identical values. TI\'s list has no separate "transaction amount" for `TnxAmount`, but it does have `TAVE` = "%s", which is probably what `AvailableAmt` should use instead of `OUA`.' % EVENT_LISTS[DESC_SOURCE][0].get(('TAVE', 'v'), 'not in the list'),
            '* **Same field name twice:** ' + ', '.join('`%s`' % n for n in dup) + '. TI\'s list explains the two `Charges` tables: `AAOC` = "%s" and `AABC` = "%s" (charges for the addressee: ours, and other banks\'). `GDOCS` = "%s"; `tAATT` is a bank-defined tag that is **not** in the IGT issue event list. A consumer must tell them apart by tag.' % (EVENT_LISTS[DESC_SOURCE][0].get(('AAOC', '*'), '?'), EVENT_LISTS[DESC_SOURCE][0].get(('AABC', '*'), '?'), EVENT_LISTS[DESC_SOURCE][0].get(('GDOCS', '*'), '?')),
            '* **Tags that are not in the IGT issue event field list:** ' + (', '.join('`%s` (field `%s`)' % (t, n) for n, t in missing) or 'none') + '. A tag outside the list cannot be filled for this event; `CMBYC` is probably meant to be `CMBY` ("Confirmed by").',
            '* **Tag reused across types:** `DAD` is both a flag and a day count, and `DFRP` both an integer and a string. Treat tag **and** type as the key.',
            ] + (['* **Fields with no inbound counterpart and no recognised purpose** (%d): %s.' % (len(unmapped), ', '.join('`%s`' % n for n in unmapped))] if unmapped else []) + [
            '* **%d fields have only a low-confidence counterpart** (the renewal and reduction groups need a business check): %s.' % (len(low), ', '.join('`%s`' % n for n in low)),
            '']
    return '\n'.join(out)


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for name in ['TFUTICRT', 'TFUTIACK', 'TFUTIREJ']:
        text = render(name)
        with open(os.path.join(OUT, name + '.md'), 'w', encoding='utf8') as fh:
            fh.write(text.rstrip() + '\n')
        print('wrote', name, len(text.splitlines()), 'lines')
