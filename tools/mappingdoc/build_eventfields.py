"""Render docs/outbound/event-fields-<STEM>.md from sources/ti_outbound/<STEM>_All_E.csv.

    python3 -I tools/mappingdoc/build_eventfields.py
"""
import collections
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import eventfields_lib as E  # noqa: E402
import mapping_lib as M  # noqa: E402

OUT = os.path.join(E.ROOT, 'docs', 'outbound')
LABEL = {'IGT_IIG': ('IGT issue event', 'IGT-IIG')}
THEMES = [
    ('Shipment parties, vessels, ports (numbered 1 to 5)', r'vessel|port|airport|consignee|notify|shipper|carrier|agent|master|manufacturer|transport|insurance|settling|survey|other bank|other part|place/city|charterer|freight|transhipment|imo|shipment|shipping'),
    ('Electronic bank guarantee (eBG)', r'ebg'),
    ('Regulatory codes (purpose of transaction, document type)', r'sandi'),
    ('Fixed deposit and margin', r'\bfd\b|held as margin'),
    ('Dealer financing', r'dealer|ktp|profit margin'),
    ('Extension, notice and reminder dates', r'extension|notice|reminder|claim period'),
    ('Goods and invoice', r'goods|hs code|invoice|incoterm|country of'),
    ('Event user-defined codes (`ev…`)', r'undertaking guarantee sub type|change in credit|user defined code'),
]


def theme(code, desc):
    for name, rx in THEMES:
        if re.search(rx, desc, re.I):
            return name
    return 'Other'


def render(stem):
    path = os.path.join(E.ROOT, 'sources', 'ti_outbound', stem + '_All_E.csv')
    fields, sections = E.load(path)
    rows = list(csv.reader(open(path, encoding='utf-8-sig', newline='')))
    n_rows = sum(1 for r in rows if len(r) == 3)
    header = next(r for r in rows if len(r) == 5)[:3]
    per_section = collections.Counter()
    cur = None
    dupes = []
    seen = set()
    for r in rows:
        if len(r) == 5:
            cur = r[3]
        elif len(r) == 3:
            per_section[cur] += 1
            if (cur, r[0]) in seen:
                dupes.append((cur, r[0]))
            seen.add((cur, r[0]))
    used = {(f['tag'], f['type']) for g in M.load('TFUTICRT') for f in g if f['type'] != 'literal'}
    prod, ev = LABEL.get(stem, (stem, stem))
    out = ['# Event field list – %s' % prod, '',
           '> Generated by `tools/mappingdoc/build_eventfields.py` from `sources/ti_outbound/%s_All_E.csv`. Do not edit. Background: [README](README.md).' % stem, '',
           'TI exported **every event field available for this event**. It is the dictionary behind the tags of a mapping such as [`TFUTICRT`](TFUTICRT.md): '
           'a tag is usable in a message for this event only if it is in this list.', '',
           '| | |', '|---|---|',
           '| File | `sources/ti_outbound/%s_All_E.csv` |' % stem,
           '| Header cells | "%s", "%s", "%s" (repeated at the start of every section) |' % tuple(header),
           '| Entries | %d rows, %d distinct (code, type) pairs; the rows repeat a code when it exists under several types |' % (n_rows, len(fields)),
           '| Format | Sections started by a 5-cell row whose 4th cell is the **event field type**; each following 3-cell row is `code, description` |',
           '']

    out += ['## 1. Sections are the event field types', '',
            'The 17 section names match the event field types of the TI database (`EFDEFNITEM.EVFLDTYPE`), so the key of a field is **(code, type)**. The same code can exist under more than one type '
            '(for example `DAD` is both a logical "Advise reduction" and an integer "Advise notice days"; `AAOC` is both a table and a "present?" flag).', '',
            '| Section | Type letter | Entries |', '|---|---|---:|']
    for name, letter in sections:
        out.append('| %s | `%s` | %d |' % (name, letter, per_section[name]))
    out += ['']

    out += ['## 2. Name families: -U, -R, -S, -M', '',
            'Many codes come in four variants that differ only in the suffix. TI states the meaning in the description:', '',
            '| Suffix | Meaning (from the descriptions) | Entries | Used by `TFUTICRT` |', '|---|---|---:|---:|']
    for suf, name in E.FAMILY.items():
        avail = {k for k in fields if E.family(k[0]) == suf}
        out.append('| `-%s` | %s | %d | %d |' % (suf, name, len(avail), len(avail & used)))
    plain = {k for k in fields if not E.family(k[0])}
    out += ['| (none) | not a family field | %d | %d |' % (len(plain), len(plain & used)), '',
            'This settles the `-U` / `-S` question in the README: **`-U` is the undertaking, `-S` the counter-undertaking to send**, and the list also has `-R` (counter received) and `-M` (main), which `TFUTICRT` does not use.', '']

    found = sorted(k for k in used if k in fields)
    missing = sorted(k for k in used if k not in fields)
    out += ['## 3. Coverage of `TFUTICRT`', '',
            '`TFUTICRT` uses %d distinct (tag, type) pairs. **%d are in this list; %d are not:**' % (len(used), len(found), len(missing)), '']
    if missing:
        out += ['| Tag | Type | Used by field | Likely reason |', '|---|---|---|---|']
        names = {}
        for g in M.load('TFUTICRT'):
            for f in g:
                names.setdefault((f['tag'], f['type']), f['name'])
        reasons = {'CMBYC': 'The list has `CMBY` ("Confirmed by") and `CCPBC`; `CMBYC` looks like a typo',
                   'tAATT': 'Lower-case `t…` is a bank-defined tag; it is not defined for this event'}
        for t, ty in missing:
            out.append('| `%s` | `%s` | `%s` | %s |' % (t, ty, names[(t, ty)], reasons.get(t, '')))
        out.append('')

    custom = sorted((k, v) for k, v in fields.items() if re.match(r'[a-z]', k[0]))
    groups = collections.defaultdict(list)
    for k, v in custom:
        groups[theme(k[0], v)].append(k)
    out += ['## 4. Bank-defined fields', '',
            'Codes that start with a lower-case letter are **bank-defined** (`cAA…`, `cAB…`, `evPU…`): %d entries. Most come as a pair, an event-level field and a master-level field whose description ends in `(M)`. '
            'They are the bank\'s customisation of TI and **the standard gateway schema in `sources/xsd_element_docs` does not describe them**.' % len(custom), '',
            '| Theme | Entries |', '|---|---:|']
    for name in [t[0] for t in THEMES] + ['Other']:
        if groups.get(name):
            out.append('| %s | %d |' % (name, len(groups[name])))
    out += ['',
            'Consequence: if the new channel must send or show these (eBG, regulatory codes, shipment parties, fixed-deposit details), the bank\'s **customised gateway message definitions** are needed. The standard `TFUTIAPP` has only `AdditionalData/DataItem` (name/value, "recorded as event notifications") and an empty `ExtraData`. See open question Q25.', '']

    unusedU = sorted(k for k in fields if E.family(k[0]) == 'U' and k not in used)
    out += ['## 5. `-U` fields that `TFUTICRT` does not use (%d)' % len(unusedU), '',
            'Candidates to add to a response, or to ignore. The `-S`, `-R` and `-M` twins exist for each.', '',
            '| Code | Type | Description |', '|---|---|---|']
    for (c, t) in unusedU:
        out.append('| `%s` | `%s` | %s |' % (c, t, fields[(c, t)]))
    out += ['']

    out += ['## 6. Anomalies in the file', '',
            '* **Rows listed twice in the same section** (%d): %s. Harmless; the reader keeps the first.' % (len(dupes), ', '.join('`%s` (%s)' % (c, s) for s, c in dupes) or 'none'),
            '* **HTML entities in descriptions** (`&apos;`): the reader decodes them.',
            '* **Not in the list although the type exists in the database** (`+` list, `-` address, `q` party settlement, `f` system account, `x` watch-list party): these types have no section in this file.', '']

    out += ['## 7. Searching', '', '```',
            'python3 -I tools/mappingdoc/eventfields_lib.py search "renewal"     # words in code or description',
            'python3 -I tools/mappingdoc/eventfields_lib.py code EXP-U           # one code, all types',
            '```', '',
            'To add another event or product, export its list the same way and save it as `sources/ti_outbound/<PRODUCT>_<EVENT>_All_E.csv`; the reader picks up every `*_All_E.csv`.', '']
    return '\n'.join(out), 'event-fields-%s.md' % ev


if __name__ == '__main__':
    for stem in E.load_all():
        if ':' in stem:
            # A list of every event of a product (FSA_All, 22 000 rows) is searched, not printed.
            continue
        text, name = render(stem)
        with open(os.path.join(OUT, name), 'w', encoding='utf8') as fh:
            fh.write(text.rstrip() + '\n')
        print('wrote', name, len(text.splitlines()), 'lines')
