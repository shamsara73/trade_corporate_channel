"""Render docs/reference/xsd-jars.md: TI's real XSDs (the jars in sources/) compared with the
gateway documentation the catalogue and product specs are built from, plus the bank's ExtraData.

    python3 -I tools/xsdcheck/build_xsd_report.py

Sample validation (section 4) needs lxml; without it that section says so and the rest is built.
"""
import collections
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [HERE, os.path.join(HERE, '..', 'specgen'), os.path.join(HERE, '..', 'mappingdoc')]
import xsd_lib as X  # noqa: E402
import specgen_lib as L  # noqa: E402
import eventfields_lib as E  # noqa: E402
import mapping_lib as M  # noqa: E402

OUT = os.path.join(X.ROOT, 'docs', 'reference', 'xsd-jars.md')
DOCS_VERSION = '2.11.5.2.J'
PARTY_PARTS = ('MXAddress', 'SwiftTradeAddress')


def doc_messages():
    names = os.listdir(os.path.join(X.ROOT, 'sources', 'xsd_element_docs'))
    return sorted(m.group(1) for m in (re.match(r'TI\.(TF\w+)\.xsd\.txt$', n) for n in names) if m)


def doc_paths(code):
    return {n.path for n in L.parse(code).walk() if not (n.path == 'ExtraData' or n.path.startswith('ExtraData/'))}


def pattern(path):
    """Collapse the same difference repeated under every party into one pattern."""
    parts = path.split('/')
    for i, p in enumerate(parts):
        if p in PARTY_PARTS or p.startswith('MXAddress.'):
            return '<party>/' + '/'.join(parts[i:])
    return path


def main():
    S = X.Schemas()
    jar, docs = set(S.messages()), set(doc_messages())
    both = sorted(jar & docs)
    diffs = {m: (doc_paths(m) - set(S.paths(m)), set(S.paths(m)) - doc_paths(m)) for m in both}
    patterns = collections.Counter()
    for m, (only_docs, only_jar) in diffs.items():
        patterns.update(('documentation only', p) for p in {pattern(x) for x in only_docs})
        patterns.update(('XSD only', p) for p in {pattern(x) for x in only_jar})
    common = {k for k, v in patterns.items() if v >= 18}

    out = ['# TI XSD jars compared with the gateway documentation', '',
           '> Generated by `tools/xsdcheck/build_xsd_report.py` from `sources/com.misys.tiplus2.gen.ti-xsd.jar`, '
           '`sources/com.misys.tiplus2.gen.ti-xsd.customisation.jar`, `sources/xsd_element_docs/` and `sources/ti_outbound/`. Do not edit.', '',
           '## 1. Versions', '',
           '| Source | Version | Messages (`TF…`) |', '|---|---|---:|',
           '| Gateway documentation (`sources/xsd_element_docs/`, `sources/example_xml/`) – what the catalogue and product specs are built from | %s | %d |' % (DOCS_VERSION, len(docs)),
           '| XSD jar (`ti-xsd.jar`, manifest `Implementation-Version`) – what TI validates inbound messages against | %s | %d |' % (X.manifest_version(), len(jar)),
           '',
           '**The jars are an older, bank-specific build (2.10.3.1) than the documentation (2.11.5.2.J).** Where they differ, '
           'a message built from the documentation can be rejected by TI. Which version production will run is open question Q32; '
           'until it is answered, the jar wins (working assumption).', '',
           '## 2. Messages', '',
           '* In the documentation but **not in the jar** (%d): %s.' % (len(docs - jar), ', '.join('`%s`' % m for m in sorted(docs - jar))),
           '* In the jar but not in the documentation (%d): %s.' % (len(jar - docs), ', '.join('`%s`' % m for m in sorted(jar - docs)) or 'none'),
           '* In both: %d, of which %d have identical element paths (ignoring `ExtraData`).' % (len(both), sum(1 for d in diffs.values() if not d[0] and not d[1])), '',
           '## 3. Differences inside messages', '',
           'Paths compare element names only (not types or lengths). `<party>` stands for any party block (`Applicant`, `Beneficiary`, `AdviseThru`, …).', '',
           '### 3.1 Differences that repeat across messages', '',
           '| Where | Path | Messages |', '|---|---|---:|']
    for (side, p), n in sorted(patterns.items(), key=lambda kv: (-kv[1], kv[0])):
        if (side, p) in common:
            out.append('| %s | `%s` | %d |' % (side, p, n))
    out += ['',
            'Meaning: the bank build has **no** `SwiftTradeAddress`, no nested `MXAddress/AddressLine1-2`, no `EmbeddedItems/IsCustomerAttachedDocument`, `DocumentFileName`, `TransportDocRef`, and no `ExternalReview` block; '
            'its structured (ISO 20022) address for additional parties is a flat list of `MXAddress.<Part>` elements instead of a nested `MXAddress` block.', '',
            '### 3.2 Other differences, by message', '',
            '| Message | Only in documentation | Only in XSD |', '|---|---|---|']
    for m in both:
        a = sorted({pattern(x) for x in diffs[m][0]} - {p for s, p in common if s == 'documentation only'})
        b = sorted({pattern(x) for x in diffs[m][1]} - {p for s, p in common if s == 'XSD only'})
        if a or b:
            shared = doc_paths(m) & set(S.paths(m))

            def cell(items):
                # `X` = the element is missing on the other side; `X/…` = X exists on both, something inside differs.
                tops = sorted({i if i.startswith('<party>') else
                               (i.split('/')[0] + '/…' if i.split('/')[0] in shared else i.split('/')[0]) for i in items})
                shown = ', '.join('`%s`' % t for t in tops[:12])
                return shown + (' and %d more' % (len(tops) - 12) if len(tops) > 12 else '') if tops else '–'
            out.append('| `%s` | %s | %s |' % (m, cell(a), cell(b)))
    out += ['', '`X` means the element is missing on the other side; `X/…` means `X` exists in both but something inside it differs. Run `python3 -I tools/xsdcheck/xsd_lib.py paths <MESSAGE>` for the full list.', '']

    out += ['## 4. Samples in the documents, validated against the jar', '']
    try:
        import check_samples
        results = check_samples.validate()
        bad = [r for r in results if r[2]]
        out += ['%d samples checked (`python3 -I tools/xsdcheck/check_samples.py`); %d valid, %d rejected:' % (len(results), len(results) - len(bad), len(bad)), '',
                '| Sample | Message | First error |', '|---|---|---|']
        out += ['| `%s` | `%s` | %s |' % (s, op, L.esc(errs[0])) for s, op, errs in bad]
        out += ['', 'Every rejection is a 2.11 element or message missing from the bank build (section 3). The samples stay as they are until Q32 is answered.', '']
    except SystemExit as e:
        out += ['Not run: %s' % e, '']

    out += ['## 5. Header (control schema)', '',
            '* `Credentials` children are `Name`, `Password`, `Certificate`, `Digest` – **`Name`, not `User`** as the SDK guide shows (answers Q31).',
            '* `CreationDate` is `xs:date` (a business date, `2026-10-18`), not a timestamp. The samples were corrected.',
            '* Element order in `RequestHeader`: `Service`, `Operation`, `Credentials`, `ReplyFormat`, `ReplyTarget`, `TargetSystem`, `SourceSystem`, `NoRepair`, `NoOverride`, `CorrelationId`, `TransactionControl`, `CreationDate`, `GroupingId`. The samples had `SourceSystem` before `TargetSystem` and were corrected.',
            '* `CorrelationId` at most 48 characters; `GroupingId` at most 80; `ReplyTarget` is `xs:anyURI`.',
            '* Schema defaults: `ReplyFormat` = `FULL`, `NoRepair` = `Y`, `NoOverride` = `Y`, `TransactionControl` = `NONE` (the SDK guide says `N` for the two flags; send them explicitly).', '']

    # ExtraData
    by_type = collections.defaultdict(list)
    for m in sorted(jar):
        t = S.extra_type(m)
        if t:
            by_type[t].append(m)
    out += ['## 6. Bank-defined fields (`ExtraData`)', '',
            'Each message\'s `ExtraData` has a type from the customisation jar (namespace `urn:custom.service.ti.apps.tiplus2.misys.com`). '
            'Each field carries its event field code in `msg.event.code`; the event field is that code with a `c` prefix (`AAU` → `cAAU`). '
            '%d messages share %d `ExtraData` types; %d messages have none.' % (sum(len(v) for v in by_type.values()), len(by_type), len(jar) - sum(len(v) for v in by_type.values())), '']
    lists = E.load_all()
    if 'IGT_IIG' in lists:
        fields = lists['IGT_IIG'][0]
        desc = {}
        for (code, _typ), d in fields.items():
            desc.setdefault(code, d)
        used = {f['tag'] for g in M.load('TFUTICRT') for f in g if f['type'] != 'literal'}
        extra = S.extra_fields('TFIGTAPP')
        tops = [(p, c, t) for p, c, t in extra if '/' not in p]
        out += ['### 6.1 Guarantee Issued issue event (`TFIGTAPP`, type `%s`)' % S.extra_type('TFIGTAPP'), '',
                '%d fields (%d top-level). "In IGT list" = the code is in TI\'s event field list for the IGT issue event (`IGT_IIG_All_E.csv`); "In TFUTICRT" = TI sends it back in the issued message.' % (len(extra), len(tops)), '',
                '| `ExtraData` element | Event field | XSD type | In IGT list (description) | In `TFUTICRT` |', '|---|---|---|---|---|']
        for p, code, typ in extra:
            if '/' in p:
                # A column of a repeating table: its code is local to the table, not an event field.
                out.append('| `%s` | column `%s` | `%s` | – | |' % (p, code, typ))
                continue
            ev = ('c' + code) if code else ''
            out.append('| `%s` | %s | `%s` | %s | %s |' % (p, '`%s`' % ev if ev else '–', typ,
                                                         L.esc(desc[ev]) if ev in desc else ('**no**' if ev else '–'),
                                                         'yes' if ev in used else ''))
        lower = sorted(c for c in desc if c[:1].islower())
        in_extra = {('c' + c) for p, c, _ in extra if c and '/' not in p}
        out += ['', '* The IGT list has %d lower-case (bank-defined) codes; %d of them are `ExtraData` fields of `TFIGTAPP`. The others (for example `t…`, `ev…` codes and `c…` codes of other screens) cannot be sent by the channel on this message.' % (len(lower), len(in_extra & set(lower))),
                '* Bank-defined codes used by `TFUTICRT` that are **not** `ExtraData` fields of `TFIGTAPP`: %s.' % (', '.join('`%s`' % c for c in sorted(u for u in used if u[:1].islower() and u not in in_extra)) or 'none'), '']
    out += ['### 6.2 All `ExtraData` types', '', '| Type | Fields | Messages |', '|---|---:|---|']
    for t in sorted(by_type):
        out.append('| `%s` | %d | %s |' % (t, len(S.extra_fields(by_type[t][0])), ', '.join('`%s`' % m for m in by_type[t])))
    out += ['', '## 7. How to use this', '',
            '```', 'python3 -I tools/xsdcheck/xsd_lib.py paths TFIGTAPP    # element paths in the jar',
            'python3 -I tools/xsdcheck/xsd_lib.py extra TFIGTAPP    # ExtraData fields with event codes',
            'python3 -I tools/xsdcheck/check_samples.py            # validate every sample (needs lxml)',
            'python3 -I tools/xsdcheck/build_xsd_report.py         # regenerate this page', '```', '']
    with open(OUT, 'w', encoding='utf8') as fh:
        fh.write('\n'.join(out))
    print('wrote', os.path.relpath(OUT, X.ROOT), len(out), 'lines')


if __name__ == '__main__':
    main()
